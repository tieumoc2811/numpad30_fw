static void cmd(uint8_t c) {
    uint8_t b[2] = {0x00, c};
    i2c_write_blocking(bus, OLED_ADDR, b, 2, false);
}

void oled_init(i2c_inst_t *i2c, uint sda, uint scl) {
    bus = i2c;
    i2c_init(bus, 400 * 1000);
    gpio_set_function(sda, GPIO_FUNC_I2C);
    gpio_set_function(scl, GPIO_FUNC_I2C);
    gpio_pull_up(sda);
    gpio_pull_up(scl);
    sleep_ms(50);

    static const uint8_t init[] = {
        0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40,
        0x8D, 0x14, 0x20, 0x02, 0xA1, 0xC8, 0xDA, 0x12,
        0x81, 0xCF, 0xD9, 0xF1, 0xDB, 0x40, 0xA4, 0xA6, 0xAF,
    };
    for (size_t i = 0; i < sizeof init; i++) cmd(init[i]);
    oled_clear();
    oled_flush();
}

void oled_clear(void) { memset(fb, 0, sizeof fb); }

static void px(int x, int y) {
    if (x < 0 || x >= W || y < 0 || y >= H) return;
    fb[(y >> 3) * W + x] |= (uint8_t)(1u << (y & 7));
}

void oled_text(int x, int y, const char *s, int scale) {
    for (; *s; s++) {
        int ch = toupper((unsigned char)*s);
        if (ch < 32 || ch > 95) ch = '?';
        const uint8_t *g = font5x7[ch - 32];
        for (int col = 0; col < 5; col++)
            for (int row = 0; row < 7; row++)
                if (g[col] & (1u << row))
                    for (int dx = 0; dx < scale; dx++)
                        for (int dy = 0; dy < scale; dy++)
                            px(x + col * scale + dx, y + row * scale + dy);
        x += 6 * scale;
    }
}

void oled_flush(void) { dirty = true; page = 0; }

void oled_service(void) {
    if (!dirty) return;
    cmd(0xB0 | page);
    cmd(0x00);
    cmd(0x10);
    uint8_t buf[W + 1];
    buf[0] = 0x40;
    memcpy(&buf[1], &fb[page * W], W);
    i2c_write_blocking(bus, OLED_ADDR, buf, sizeof buf, false);
    if (++page >= H / 8) { page = 0; dirty = false; }
}

void oled_flush_now(void) { oled_flush(); while (dirty) oled_service(); }

void oled_fill(int x, int y, int w, int h) {
    for (int j = 0; j < h; j++) for (int i = 0; i < w; i++) px(x + i, y + j);
}

void oled_set_flip(bool flip) { cmd(flip ? 0xA0 : 0xA1); cmd(flip ? 0xC0 : 0xC8); }
void oled_set_contrast(uint8_t c) { cmd(0x81); cmd(c); }
void oled_power(bool on) { cmd(on ? 0xAF : 0xAE); }

bool oled_busy(void) { return dirty; }

void oled_clr(int x, int y, int w, int h) {
    for (int j = 0; j < h; j++)
        for (int i = 0; i < w; i++) {
            int px_ = x + i, py_ = y + j;
            if (px_ >= 0 && px_ < W && py_ >= 0 && py_ < H) fb[(py_ >> 3) * W + px_] &= (uint8_t)~(1u << (py_ & 7));
        }
}
